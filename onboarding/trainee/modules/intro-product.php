<section class="learning-module">
  <p class="eyebrow">MODULE 01 / PRODUCT OPERATIONS</p>
  <h2>Product Catalog and Request Flow</h2>
  <p>Use the catalog as the shared reference for item details, pricing, availability, and customer-facing descriptions.</p>
  <div class="key-highlight">
    <h3>Learning objectives</h3>
    <ul>
      <li>Locate the authoritative product record and confirm its current status.</li>
      <li>Review category, package, price, inventory, and approved description fields.</li>
      <li>Connect a sample or customer request to its originating record.</li>
      <li>Escalate missing or conflicting information before promising an outcome.</li>
    </ul>
  </div>
  <h3>Use a consistent review sequence</h3>
  <ol>
    <li>Confirm the requested item and customer context.</li>
    <li>Check current availability and the correct fulfillment path.</li>
    <li>Record the request with its reference and next owner.</li>
    <li>Close the loop after the status changes.</li>
  </ol>
  <p class="pro-tip"><strong>Working principle:</strong> Keep the catalog, request, and follow-up connected so every handoff has context.</p>
