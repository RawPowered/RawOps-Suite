-- ============================================================================
-- Email Workflow Conditional Logic & Decision Trees
-- Date: 2025-10-11
-- Purpose: Enable workflow chaining with conditional branching
-- ============================================================================

-- ============================================================================
-- 1. Workflow Template Content - Store AI-generated preview content
-- ============================================================================
CREATE TABLE IF NOT EXISTS `email_workflow_templates` (
  `id` int(11) UNSIGNED NOT NULL AUTO_INCREMENT,
  `workflow_id` int(11) UNSIGNED NOT NULL COMMENT 'Parent workflow',
  `subject_template` varchar(500) DEFAULT NULL COMMENT 'Email subject template',
  `body_template` mediumtext DEFAULT NULL COMMENT 'AI-generated or static HTML body',
  `is_ai_generated` tinyint(1) DEFAULT 0 COMMENT 'Was this generated by AI preview',
  `ai_prompt_used` text DEFAULT NULL COMMENT 'Original AI prompt if AI-generated',
  `variables` json DEFAULT NULL COMMENT 'Template variables for personalization',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_workflow` (`workflow_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Pre-generated workflow email content';

-- ============================================================================
-- 2. Workflow Conditions - Decision tree logic
-- ============================================================================
CREATE TABLE IF NOT EXISTS `email_workflow_conditions` (
  `id` int(11) UNSIGNED NOT NULL AUTO_INCREMENT,
  `workflow_id` int(11) UNSIGNED NOT NULL COMMENT 'Workflow this condition belongs to',
  `condition_type` enum('email_opened','email_clicked','conversion_type','conversion_value','time_elapsed','day_of_week','reply_received','custom') NOT NULL,
  `operator` enum('equals','not_equals','greater_than','less_than','contains','in_range') NOT NULL DEFAULT 'equals',
  `condition_value` varchar(255) DEFAULT NULL COMMENT 'Value to compare against',
  `condition_metadata` json DEFAULT NULL COMMENT 'Additional condition parameters',
  `next_workflow_id_true` int(11) UNSIGNED DEFAULT NULL COMMENT 'Workflow to trigger if condition TRUE',
  `next_workflow_id_false` int(11) UNSIGNED DEFAULT NULL COMMENT 'Workflow to trigger if condition FALSE',
  `priority` int(11) DEFAULT 50 COMMENT 'Order of evaluation for multiple conditions',
  `is_active` tinyint(1) DEFAULT 1,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_workflow` (`workflow_id`),
  KEY `idx_next_true` (`next_workflow_id_true`),
  KEY `idx_next_false` (`next_workflow_id_false`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Conditional branching logic for workflows';

-- ============================================================================
-- 3. Workflow Chains - Track multi-step sequences
-- ============================================================================
CREATE TABLE IF NOT EXISTS `email_workflow_chains` (
  `id` int(11) UNSIGNED NOT NULL AUTO_INCREMENT,
  `chain_name` varchar(255) NOT NULL COMMENT 'Name for this workflow sequence',
  `description` text DEFAULT NULL,
  `owner_agent_id` int(11) UNSIGNED DEFAULT NULL COMMENT 'Agent who created this chain',
  `root_workflow_id` int(11) UNSIGNED NOT NULL COMMENT 'Starting workflow in the chain',
  `is_active` tinyint(1) DEFAULT 1,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_root` (`root_workflow_id`),
  KEY `idx_owner` (`owner_agent_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Multi-step workflow sequences with decision trees';

-- ============================================================================
-- 4. Extend email_followup_workflows for chaining
-- ============================================================================
ALTER TABLE `email_followup_workflows`
ADD COLUMN IF NOT EXISTS `has_conditions` tinyint(1) DEFAULT 0 COMMENT 'Flag: this workflow has conditional branching' AFTER `is_active`,
ADD COLUMN IF NOT EXISTS `chain_id` int(11) UNSIGNED DEFAULT NULL COMMENT 'Part of a workflow chain' AFTER `has_conditions`,
ADD COLUMN IF NOT EXISTS `chain_step` int(11) DEFAULT 0 COMMENT 'Step number in chain (0=root)' AFTER `chain_id`,
ADD KEY IF NOT EXISTS `idx_chain` (`chain_id`);

-- ============================================================================
-- 5. Extend email_followup_schedule for chain tracking
-- ============================================================================
ALTER TABLE `email_followup_schedule`
ADD COLUMN IF NOT EXISTS `chain_id` int(11) UNSIGNED DEFAULT NULL COMMENT 'Part of a workflow chain' AFTER `workflow_id`,
ADD COLUMN IF NOT EXISTS `chain_step` int(11) DEFAULT 0 COMMENT 'Current step in chain' AFTER `chain_id`,
ADD COLUMN IF NOT EXISTS `condition_result` json DEFAULT NULL COMMENT 'Results of condition evaluation' AFTER `chain_step`,
ADD KEY IF NOT EXISTS `idx_chain` (`chain_id`);

-- ============================================================================
-- 6. Workflow execution history for debugging chains
-- ============================================================================
CREATE TABLE IF NOT EXISTS `email_workflow_execution_log` (
  `id` int(11) UNSIGNED NOT NULL AUTO_INCREMENT,
  `schedule_id` int(11) UNSIGNED NOT NULL COMMENT 'Reference to email_followup_schedule',
  `workflow_id` int(11) UNSIGNED NOT NULL,
  `agent_email_id` int(11) UNSIGNED NOT NULL COMMENT 'The email being processed',
  `step_number` int(11) DEFAULT 0,
  `condition_evaluated` json DEFAULT NULL COMMENT 'Conditions checked',
  `decision_made` varchar(50) DEFAULT NULL COMMENT 'true, false, or none',
  `next_workflow_id` int(11) UNSIGNED DEFAULT NULL COMMENT 'Which workflow was triggered next',
  `execution_time_ms` int(11) DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_schedule` (`schedule_id`),
  KEY `idx_workflow` (`workflow_id`),
  KEY `idx_email` (`agent_email_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Workflow execution history for debugging';

-- ============================================================================
-- 7. AI Template Generation History
-- ============================================================================
CREATE TABLE IF NOT EXISTS `workflow_ai_generations` (
  `id` int(11) UNSIGNED NOT NULL AUTO_INCREMENT,
  `workflow_id` int(11) UNSIGNED NOT NULL,
  `agent_id` int(11) UNSIGNED NOT NULL COMMENT 'Who generated this',
  `prompt_text` text NOT NULL,
  `generated_subject` varchar(500) DEFAULT NULL,
  `generated_body` mediumtext DEFAULT NULL,
  `model_used` varchar(100) DEFAULT 'gemini-2.0-flash-exp',
  `generation_time_ms` int(11) DEFAULT NULL,
  `was_approved` tinyint(1) DEFAULT 0 COMMENT 'Agent approved this as template',
  `approved_at` datetime DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_workflow` (`workflow_id`),
  KEY `idx_agent` (`agent_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI-generated workflow template history';

