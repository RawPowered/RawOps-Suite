  <p class="eyebrow">PRODUCT QUALITY / FIELD GUIDE</p>
  <h1>Product Quality Basics</h1>
  <p>A consistent product operation begins with accurate catalog data, documented supplier information, traceable inventory, and clear customer communication.</p>
  <h2>Review the catalog record</h2>
  <ul>
    <li>Confirm the item name, category, package size, and current status.</li>
    <li>Use approved product descriptions and avoid claims that are not documented.</li>
    <li>Keep images and specifications connected to the correct catalog record.</li>
  </ul>
  <h2>Keep the order trail clear</h2>
  <p>Sample requests, inventory changes, invoices, and follow-up should retain a shared reference so the next team member can understand what happened.</p>
  <h2>Escalate uncertainty</h2>
  <p>When a specification or customer question is unclear, record the question and route it to an authorized reviewer before making a commitment.</p>
