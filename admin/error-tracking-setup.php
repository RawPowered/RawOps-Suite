$setupStatus = [];

// Check if migration has been run
function checkTable($pdo, $tableName) {
    try {
        $stmt = $pdo->query("SHOW TABLES LIKE '$tableName'");
        return $stmt->rowCount() > 0;
    } catch (Exception $e) {
        return false;
    }
}

// Run migration if requested
if (isset($_POST['run_migration'])) {
    try {
        $migrationFile = __DIR__ . '/../migrations/2025-09-30-error-tracking-system.sql';
        if (!file_exists($migrationFile)) {
            throw new Exception('Migration file not found');
        }

        $sql = file_get_contents($migrationFile);
        $pdo->exec($sql);
        $setupStatus['migration'] = ['success' => true, 'message' => 'Migration completed successfully!'];
    } catch (Exception $e) {
        $setupStatus['migration'] = ['success' => false, 'message' => 'Migration failed: ' . $e->getMessage()];
    }
}

// Insert test error if requested
if (isset($_POST['insert_test_error'])) {
    try {
        log_error_to_database([
            'error_type' => 'custom',
            'error_code' => 'TEST_ERROR',
            'error_message' => 'This is a test error generated by the setup script to verify error tracking is working correctly.',
            'error_severity' => 'warning',
            'url' => $_SERVER['REQUEST_URI'],
        ]);
        $setupStatus['test'] = ['success' => true, 'message' => 'Test error inserted successfully!'];
    } catch (Exception $e) {
        $setupStatus['test'] = ['success' => false, 'message' => 'Failed to insert test error: ' . $e->getMessage()];
    }
}

