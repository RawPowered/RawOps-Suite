    ]
];

// Count error records
$errorCount = 0;
$alertCount = 0;
try {
    if (checkTable($pdo, 'error_log_detailed')) {
        $errorCount = (int)$pdo->query("SELECT COUNT(*) FROM error_log_detailed")->fetchColumn();
    }
    if (checkTable($pdo, 'error_alerts')) {
        $alertCount = (int)$pdo->query("SELECT COUNT(*) FROM error_alerts WHERE is_acknowledged = 0")->fetchColumn();
    }
} catch (Exception $e) {
    // Ignore
}

